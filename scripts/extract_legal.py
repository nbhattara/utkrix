"""Converts the supplied legal text into structured JS data, verbatim.

Usage:
  python3 scripts/extract_legal.py scripts/privacy_policy.txt src/data/dataNotice.js privacyPolicy
  python3 scripts/extract_legal.py scripts/terms_of_service.txt src/data/usageAgreement.js termsOfService

Only line wraps are joined. No legal text is written or changed by this script.
"""
import sys, re, json

src, out, name = sys.argv[1:4]
raw = open(src, encoding="utf-8", errors="replace").read().replace("\r", "").replace("\x02", "-")
is_terms = "TERMS OF SERVICE" in raw[:200]
BUL = "\uf0b7"

lines = [
    l for l in raw.split("\n")
    if not (l.startswith("UTKRIX TECHNOLOGIES |") or l.startswith("Utkrista Shikshya Pvt Ltd •") or l.strip() == "END OF PRIVACY POLICY")
]

# Real sections start at the last "1. ..." line (the Terms also have a contents list).
starts = [i for i, l in enumerate(lines) if re.match(r"^1\.\s+\S", l)]
first = starts[-1] if is_terms else starts[0]
cover, body = lines[:first], lines[first:]

LABELS = ["Legal entity", "Legal Entity", "Address", "Contact email", "Contact Email",
          "Effective / Last updated", "Brand Name"]
meta, rest = [], []
for c in (x.strip() for x in cover if x.strip()):
    lab = next((L for L in sorted(LABELS, key=len, reverse=True) if c.startswith(L + " ")), None)
    if lab:
        meta.append([lab, c[len(lab):].strip()])
    elif c.startswith("Effective Date:"):
        meta.append(["Effective Date", c.split(":", 1)[1].strip()])
    elif c.startswith("Version "):
        meta.append(["Version", c[8:].strip()])
    else:
        rest.append(c)

if is_terms:
    title, subtitle = "Terms of Service", rest[2]
    intro = " ".join(rest[3:])
    # keep Version / Effective Date first, as on the cover
    meta.sort(key=lambda m: 0 if m[0] in ("Version", "Effective Date") else 1)
else:
    title, subtitle = "Privacy Policy", ""
    intro = " ".join(rest[2:])

sections, cur, para, bul = [], None, [], None
MAXLEN = max(len(l.rstrip()) for l in body)


def is_end(l):
    """A paragraph/bullet ends on a line that finishes a sentence and is shorter than the wrap width."""
    t = l.rstrip()
    return bool(t) and t[-1] in ".:;?!”)" and len(t) < MAXLEN * 0.9


LAST_ID = "21" if is_terms else "20"
KV = ("Brand Name ", "Legal Entity ", "Address ", "Email ")
CONTACT = ("UtkriX Technologies", "Operated by Utkrista Shikshya Pvt Ltd", "Damak-09, Jhapa, Nepal")


def flush_para():
    global para
    if para and cur is not None:
        cur["blocks"].append({"t": "p", "text": " ".join(s.strip() for s in para)})
    para = []


def add_bullet(txt):
    last = cur["blocks"][-1] if cur["blocks"] else None
    if last and last["t"] == "ul" and cur.get("_ul"):
        last["items"].append(txt)
    else:
        cur["blocks"].append({"t": "ul", "items": [txt]})
    cur["_ul"] = True


for l in body:
    s = l.strip()
    if not s:
        continue
    m = re.match(r"^(\d+)\.\s+(.+)$", s)
    if m and int(m.group(1)) == len(sections) + 1:
        flush_para(); bul = None
        cur = {"id": m.group(1), "title": m.group(2).strip(), "blocks": []}
        sections.append(cur)
        continue
    m = re.match(r"^(\d+\.\d+)\s+(.+)$", s)
    if m and cur and m.group(1).startswith(cur["id"] + ".") and m.group(2)[:1].isupper():
        flush_para(); bul = None
        cur["blocks"].append({"t": "h", "text": f"{m.group(1)} {m.group(2).strip()}"})
        cur["_ul"] = False
        continue
    if cur and cur["id"] == LAST_ID and not para and bul is None:
        if is_terms and s.startswith(KV):
            if cur["blocks"] and cur["blocks"][-1]["t"] == "kv":
                cur["blocks"][-1]["rows"].append([s.split(" ", 1)[0] if s.startswith("Email ") or s.startswith("Address ") else s[:11], ""])
            else:
                cur["blocks"].append({"t": "kv", "rows": [["", ""]]}); cur["blocks"][-1]["rows"] = [["", ""]][:0] + [[None, None]]
            row = cur["blocks"][-1]["rows"][-1]
            key = next(k for k in KV if s.startswith(k)).strip()
            row[0], row[1] = key, s[len(key):].strip()
            continue
        if (not is_terms) and (s in CONTACT or s.startswith("Email: ")):
            if cur["blocks"] and cur["blocks"][-1]["t"] == "lines":
                cur["blocks"][-1]["items"].append(s)
            else:
                cur["blocks"].append({"t": "lines", "items": [s]})
            continue
    if s.startswith(BUL):
        flush_para()
        bul = [s[1:].strip()]
        if is_end(l):
            add_bullet(" ".join(bul)); bul = None
        continue
    if bul is not None:
        bul.append(s)
        if is_end(l):
            add_bullet(" ".join(bul)); bul = None
        continue
    para.append(s)
    if is_end(l):
        cur["_ul"] = False
        flush_para()
flush_para()
for sc in sections:
    sc.pop("_ul", None)

data = {"title": title, "subtitle": subtitle, "meta": meta, "intro": intro, "sections": sections}
hdr = "// AUTO-GENERATED by scripts/extract_legal.py from the supplied document text.\n// Content is verbatim from the supplied file. To change it, edit this file directly or re-run the script.\n"
with open(out, "w", encoding="utf-8") as f:
    f.write(hdr + f"export const {name} = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(name, "sections:", len(sections), "blocks:", sum(len(s["blocks"]) for s in sections), "meta:", meta)
